CREATE TABLE IF NOT EXISTS ai_agent_timeline_item (
    id                  BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键ID',
    session_id          VARCHAR(128) NOT NULL COMMENT '所属会话ID',
    request_id          VARCHAR(64)  NOT NULL COMMENT '所属 run requestId',
    item_id             VARCHAR(192) NOT NULL COMMENT '稳定时间线项ID',
    parent_item_id      VARCHAR(192) NULL COMMENT '父时间线项ID',
    agent_id            VARCHAR(128) NULL COMMENT 'main 或子 Agent 运行时ID',
    kind                VARCHAR(32)  NOT NULL COMMENT 'ASSISTANT_MESSAGE/REASONING/TOOL_CALL/ARTIFACT/PLAN/HITL/SUBAGENT/SYSTEM_NOTICE',
    phase               VARCHAR(16)  NOT NULL COMMENT 'INTERMEDIATE/SUMMARY/FINAL',
    status              VARCHAR(16)  NOT NULL COMMENT 'RUNNING/WAITING_INPUT/COMPLETED/FAILED/CANCELLED',
    order_key           BIGINT       NOT NULL DEFAULT 0 COMMENT '首次出现后不可变；0 表示待 live seq 分配',
    sub_order           INT          NOT NULL DEFAULT 0 COMMENT '同 order_key 内排序',
    updated_seq         BIGINT       NOT NULL DEFAULT 0 COMMENT '最后更新事件序号',
    source_type         VARCHAR(16)  NOT NULL COMMENT 'LLM/TOOL/ARTIFACT/RUN/SYSTEM',
    llm_invocation_id   BIGINT       NULL COMMENT '来源 LLM invocation ID',
    tool_invocation_id  BIGINT       NULL COMMENT '来源 tool invocation ID',
    artifact_id         BIGINT       NULL COMMENT '来源 artifact ID',
    create_time         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time         DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    deleted             TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '软删除',
    PRIMARY KEY (id),
    UNIQUE KEY uk_timeline_request_item (request_id, item_id),
    KEY idx_timeline_request_order (request_id, deleted, order_key, sub_order, id),
    KEY idx_timeline_session_order (session_id, deleted, order_key, sub_order, id),
    KEY idx_timeline_parent (session_id, parent_item_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Agent 时间线目录（非完整事件账本）';
